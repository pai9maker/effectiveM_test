#!/usr/bin/env bash
# EffectiveTube — one-command deployment for a clean Ubuntu host (also works on
# macOS with Docker Desktop).
#
#   ./deploy.sh
#
# What it does:
#   1. verifies Docker + Compose 2 (installs Docker on Ubuntu when run as root);
#   2. generates .env with random secrets on first run;
#   3. renders the SeaweedFS S3 credentials file from the template;
#   4. builds and starts the whole stack (PostgreSQL, Redis, SeaweedFS, API,
#      Alembic migration job, Celery worker);
#   5. waits for /readyz and seeds demo users/videos/comments (idempotent);
#   6. prints the URL, Swagger link and demo credentials.

set -euo pipefail

cd "$(dirname "$0")"

HTTP_PORT="${HTTP_PORT:-8081}"
COMPOSE=(docker compose)
SEED_SCRIPT="scripts/seed_demo.py"

color() { printf '\033[1;36m%s\033[0m\n' "$*"; }
warn() { printf '\033[1;33m%s\033[0m\n' "$*" >&2; }
die() { printf '\033[1;31m%s\033[0m\n' "$*" >&2; exit 1; }

# --------------------------------------------------------------------- docker
if ! command -v docker >/dev/null 2>&1; then
  if command -v apt-get >/dev/null 2>&1; then
    color "Docker не найден — устанавливаю (get.docker.com)…"
    if [ "$(id -u)" -ne 0 ]; then
      SUDO="sudo"
    else
      SUDO=""
    fi
    curl -fsSL https://get.docker.com | $SUDO sh
    $SUDO systemctl enable --now docker || true
    $SUDO usermod -aG docker "${USER:-root}" || true
  else
    die "Docker не установлен. Установите Docker Desktop / Docker Engine и повторите."
  fi
fi

if ! docker info >/dev/null 2>&1; then
  die "Docker daemon недоступен. Запустите Docker (например: sudo systemctl start docker) и повторите."
fi

if docker compose version >/dev/null 2>&1; then
  COMPOSE=(docker compose)
elif command -v docker-compose >/dev/null 2>&1; then
  COMPOSE=(docker-compose)
else
  die "Docker Compose не найден. Нужен Docker Compose v2 (плагин 'docker compose')."
fi

# ------------------------------------------------------------------ random gen
random_hex() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$1"
  else
    head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n' | cut -c "1-$(( $1 * 2 ))"
  fi
}

# ------------------------------------------------------------------------ .env
if [ -f .env ]; then
  color "Найден существующий .env — использую его."
else
  color "Генерирую .env со случайными секретами…"
  POSTGRES_PASSWORD="$(random_hex 16)"
  S3_ACCESS_KEY="et$(random_hex 8)"
  S3_SECRET_KEY="$(random_hex 24)"
  SECRET_KEY="$(random_hex 32)"
  cat > .env <<EOF
# Generated by deploy.sh — do not commit this file.
APP_NAME=EffectiveTube
ENV=production
DEBUG=false
SECRET_KEY=${SECRET_KEY}
BASE_URL=http://localhost:${HTTP_PORT}
HTTP_PORT=${HTTP_PORT}

POSTGRES_PASSWORD=${POSTGRES_PASSWORD}

S3_ACCESS_KEY=${S3_ACCESS_KEY}
S3_SECRET_KEY=${S3_SECRET_KEY}
S3_BUCKET=media

COOKIE_SECURE=false
ACCESS_TOKEN_TTL_MINUTES=30
REFRESH_TOKEN_TTL_DAYS=14
MAX_UPLOAD_BYTES=2147483648
MAX_VIDEO_DURATION_SEC=14400
TRANSCODE_TARGET_HEIGHT=720
DEMO_PASSWORD=DemoPass123!
EOF
  chmod 600 .env
fi

# shellcheck disable=SC1091
set -a
. ./.env
set +a

HTTP_PORT="${HTTP_PORT:-8081}"

# --------------------------------------------------- SeaweedFS S3 credentials
mkdir -p infra/seaweedfs
if [ ! -f infra/seaweedfs/s3.json ] \
   || ! grep -q "\"${S3_ACCESS_KEY}\"" infra/seaweedfs/s3.json 2>/dev/null; then
  color "Рендерю infra/seaweedfs/s3.json…"
  sed \
    -e "s|__S3_ACCESS_KEY__|${S3_ACCESS_KEY}|g" \
    -e "s|__S3_SECRET_KEY__|${S3_SECRET_KEY}|g" \
    infra/seaweedfs/s3.json.template > infra/seaweedfs/s3.json
  chmod 600 infra/seaweedfs/s3.json
fi

# ---------------------------------------------------------------------- start
color "Собираю и запускаю контейнеры (Postgres, Redis, SeaweedFS, app, worker)…"
"${COMPOSE[@]}" up -d --build

color "Жду готовности приложения на порту ${HTTP_PORT}…"
READY=0
for _ in $(seq 1 90); do
  code="$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:${HTTP_PORT}/readyz" || true)"
  if [ "$code" = "200" ]; then
    READY=1
    break
  fi
  sleep 2
done

if [ "$READY" -ne 1 ]; then
  warn "Приложение не ответило 200 на /readyz за 3 минуты. Последние логи:"
  "${COMPOSE[@]}" logs --tail=80 app || true
  "${COMPOSE[@]}" logs --tail=40 migrate || true
  die "Развёртывание не завершено. Проверьте 'docker compose ps' и 'docker compose logs'."
fi

# ------------------------------------------------------------------- demo data
color "Наполняю базу демо-данными (идемпотентно)…"
"${COMPOSE[@]}" exec -T app python "${SEED_SCRIPT}" || \
  warn "Скрипт демо-данных завершился с ошибкой — приложение всё равно доступно."

# ---------------------------------------------------------------------- summary
DEMO_PASSWORD="$(grep -E '^DEMO_PASSWORD=' .env | cut -d= -f2- || echo 'DemoPass123!')"

color "=================================================================="
color " EffectiveTube запущен: http://localhost:${HTTP_PORT}"
color " Swagger / OpenAPI:     http://localhost:${HTTP_PORT}/docs"
color " Проверка здоровья:     http://localhost:${HTTP_PORT}/readyz"
color "=================================================================="
echo " Демо-аккаунты (пароль: ${DEMO_PASSWORD}):"
echo "   admin      — администратор, видит /admin и журнал действий"
echo "   moderator  — модератор, видит /moderation"
echo "   viewer     — обычный зритель (есть доступ к приватному видео)"
echo "   techlab, cooking, travel, music, gaming — авторы видео"
echo
echo " Управление:"
echo "   docker compose ps            — состояние сервисов"
echo "   docker compose logs -f app   — логи приложения"
echo "   docker compose down          — остановить (данные сохраняются)"
echo "   docker compose down -v       — остановить и удалить данные"
